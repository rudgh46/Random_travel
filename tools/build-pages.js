#!/usr/bin/env node
// index.html 의 목적지 데이터를 읽어 노선별 정적 페이지를 생성한다.
//
//   node tools/build-pages.js          생성 (파일 기록)
//   node tools/build-pages.js --check  생성 결과가 저장소와 같은지만 확인
//
// 왜 정적 파일로 만드는가
//   검색엔진은 자바스크립트로 뽑히는 목적지를 색인할 수 없다. "서울에서 강릉 가는
//   고속버스" 같은 검색어로 유입되려면 목적지마다 실제 HTML 문서가 있어야 한다.
//
// 왜 빌드 결과를 저장소에 커밋하는가
//   netlify.toml 에 빌드 명령이 없다(publish = "."). 이 상태를 유지하면 배포가
//   단순히 파일 복사라서 실패할 여지가 없다. 대신 생성물이 데이터와 어긋나면
//   tests/pages.test.js 가 잡는다.
//
// 데이터는 index.html 한 곳에만 둔다. 여기서는 읽기만 하고, 페이지에 필요한
// 값은 각 페이지의 <script> 에 그 목적지 것만 인라인으로 박아 넣는다
// (별도 데이터 파일을 두면 둘이 어긋날 여지가 생긴다).
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SITE = 'https://randomtago.netlify.app';
const DIR = '노선';                    // 생성 페이지가 들어갈 상위 폴더
const MARK = '<!-- generated by tools/build-pages.js — 직접 고치지 마세요 -->';

// ── index.html 에서 선언 하나를 그대로 떼어내 평가한다 ──
// 정규식으로 중첩 배열을 파싱하면 금방 깨진다. 괄호 깊이를 세어 초기화식의
// 끝을 찾고 그 표현식만 평가한다(문자열 안의 괄호·주석은 건너뛴다).
function declSource(src, name) {
  const at = src.indexOf(`const ${name} = `);
  if (at < 0) throw new Error(`index.html 에서 ${name} 선언을 찾지 못했습니다`);
  let i = src.indexOf('=', at) + 1;
  while (/\s/.test(src[i])) i++;
  const start = i;
  let depth = 0, quote = null;
  for (; i < src.length; i++) {
    const c = src[i];
    if (quote) {
      if (c === '\\') i++;
      else if (c === quote) quote = null;
      continue;
    }
    if (c === '"' || c === "'" || c === '`') { quote = c; continue; }
    if (c === '/' && src[i + 1] === '/') { i = src.indexOf('\n', i); continue; }
    if (c === '[' || c === '{' || c === '(') depth++;
    else if (c === ']' || c === '}' || c === ')') depth--;
    else if (c === ';' && depth === 0) return src.slice(start, i);
  }
  throw new Error(`${name} 선언의 끝을 찾지 못했습니다`);
}

const evalDecl = (src, name) => new Function(`return (${declSource(src, name)})`)();

// ── 문자열 도구 ──
const esc = s => String(s)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;');

// 한글 종성 유무로 조사를 고른다. "강릉은 / 속초는" 을 손으로 맞추면 반드시 틀린다.
function hasJong(w) {
  const c = w.charCodeAt(w.length - 1);
  if (c < 0xac00 || c > 0xd7a3) return true;      // 한글이 아니면 있는 쪽으로
  return (c - 0xac00) % 28 !== 0;
}
const josa = (w, pair) => { const [a, b] = pair.split('/'); return w + (hasJong(w) ? a : b); };

const won = n => n.toLocaleString('ko-KR') + '원';
const durText = m => {
  const h = Math.floor(m / 60), mm = m % 60;
  return [h ? h + '시간' : '', mm ? mm + '분' : ''].filter(Boolean).join(' ') || '0분';
};
const slug = n => n.replace(/·/g, '-');
const mapUrl = q => 'https://map.naver.com/p/search/' + encodeURIComponent(q);

// 출발지 표기. 호남선은 같은 단지 안이지만 건물 이름이 센트럴시티라
// "서울고속버스터미널 호남선" 이라고 쓰면 현장에서 헷갈린다.
const DEPART = { gb: '서울고속버스터미널(경부·영동선)', hn: '센트럴시티터미널(호남선)' };

// ── 데이터 읽기 ──
function load() {
  const src = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
  const d = {};
  for (const name of ['DEST', 'TERM_LABEL', 'REGION_CODE', 'REGION_VIBE', 'SPOTS',
    'COORD', 'DEP_ID', 'DEP_HINT', 'TAGO_ARR_ID', 'TAGO_ARR', 'SEASIDE', 'SEARCH_CITY']) {
    d[name] = evalDecl(src, name);
  }
  return d;
}

